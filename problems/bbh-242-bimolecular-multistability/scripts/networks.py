#!/usr/bin/env python3
"""Enumeration of bimolecular (2,4,2) mass-action networks up to dynamical equivalence.

Shared module (imported by the other scripts).  Pure integer arithmetic, deterministic.
Run directly: prints the counts (27195 networks, 5716 classes); runtime < 1 s.
Environment: Python 3.12 (WSL Fedora 44); no third-party package needed.

Conventions
-----------
Species X, Y; a complex is a pair (a, b) = aX + bY with a + b <= 2 (bimolecular).  A reaction is an
ordered pair (source, product) of distinct complexes; there are 6 * 5 = 30 of them.  A network is a set of
4 reactions; it is a (2,4,2) network when its 4 reaction vectors span R^2.

Mass action: xdot = sum_j kappa_j z^{s_j} (p_j - s_j).  Grouping the reactions by source s, the vector
field is sum_s z^s w_s with w_s = sum_{j: s_j = s} kappa_j v_j.  As kappa ranges over R^4_{>0}, the tuple
(w_s)_s ranges over the product of the sets relint cone{v_j : s_j = s} (strictly positive combinations of a
finite set of vectors = relative interior of the cone they generate).  Hence two networks give the same
set of mass-action vector fields (are dynamically equivalent) iff they have the same sources and, source
by source, the same closed cone of reaction vectors.  The canonical form below encodes exactly this data,
and we also quotient by the swap X <-> Y ("perhaps after permuting species", BBH 2024, Sec. 2.2).
"""
from itertools import combinations
from math import gcd

COMPLEXES = [(0, 0), (1, 0), (0, 1), (2, 0), (1, 1), (0, 2)]
NAMES = {(0, 0): "0", (1, 0): "X", (0, 1): "Y", (2, 0): "2X", (1, 1): "X+Y", (0, 2): "2Y"}
REACTIONS = [(s, p) for s in COMPLEXES for p in COMPLEXES if s != p]
assert len(REACTIONS) == 30


def rname(r):
    return NAMES[r[0]] + "->" + NAMES[r[1]]


def vec(r):
    (s, p) = r
    return (p[0] - s[0], p[1] - s[1])


def swap_c(c):
    return (c[1], c[0])


def swap_r(r):
    return (swap_c(r[0]), swap_c(r[1]))


def prim(v):
    g = gcd(abs(v[0]), abs(v[1]))
    return (v[0] // g, v[1] // g)


def cross(a, b):
    return a[0] * b[1] - a[1] * b[0]


def half(v):
    """0 for angles in [0, pi), 1 for [pi, 2pi)."""
    return 0 if (v[1] > 0 or (v[1] == 0 and v[0] > 0)) else 1


def angle_key_cmp(a, b):
    ha, hb = half(a), half(b)
    if ha != hb:
        return ha - hb
    c = cross(a, b)
    return -1 if c > 0 else (1 if c < 0 else 0)


def sort_dirs(dirs):
    from functools import cmp_to_key
    return sorted(dirs, key=cmp_to_key(angle_key_cmp))


def cone_canon(vectors):
    """Canonical description of the closed convex cone generated by nonzero integer vectors in R^2.

    Returns one of
      ('ray', d)                      d primitive
      ('line', d)                     d primitive, normalised by half(d) == 0
      ('sector', d1, d2)              pointed 2-d cone with extreme rays d1, d2 (counterclockwise order)
      ('half', d, n)                  closed half-plane with boundary line R d (half(d)==0), inner normal side n=+1/-1
      ('plane',)
    """
    dirs = sorted(set(prim(v) for v in vectors))
    if len(dirs) == 1:
        return ('ray', dirs[0])
    ds = sort_dirs(dirs)
    k = len(ds)
    # all on a line?  (only possible with exactly two opposite directions)
    if k == 2 and cross(ds[0], ds[1]) == 0:
        d = ds[0] if half(ds[0]) == 0 else ds[1]
        return ('line', d)
    # find gaps between consecutive directions (counterclockwise), circularly
    # gap type: 'lt' (< pi), 'eq' (= pi), 'gt' (> pi)
    gaps = []
    for i in range(k):
        a, b = ds[i], ds[(i + 1) % k]
        c = cross(a, b)
        dot = a[0] * b[0] + a[1] * b[1]
        if c > 0:
            t = 'lt'
        elif c == 0:
            t = 'eq' if dot < 0 else 'lt'  # dot>0 impossible (distinct primitive dirs)
        else:
            t = 'gt'
        gaps.append((t, a, b))
    gt = [g for g in gaps if g[0] == 'gt']
    eq = [g for g in gaps if g[0] == 'eq']
    if len(gt) == 1:
        # pointed cone: extreme rays are b (start, ccw) ... a (end)
        _, a, b = gt[0]
        return ('sector', b, a)
    if len(gt) > 1:
        raise RuntimeError("impossible")
    if len(eq) >= 1:
        # half-plane: boundary line through a and b = -a; the cone lies on the side not in the empty gap
        _, a, b = eq[0]
        d = a if half(a) == 0 else b
        # inner side: the other directions lie on side sign(cross(d, v))
        others = [v for v in ds if cross(d, v) != 0]
        s = 1 if cross(d, others[0]) > 0 else -1
        assert all((cross(d, v) > 0) == (s > 0) for v in others)
        return ('half', d, s)
    return ('plane',)


def canon_network(net):
    """Dynamical-equivalence invariant of a network (without species swap)."""
    by_src = {}
    for r in net:
        by_src.setdefault(r[0], []).append(vec(r))
    return tuple(sorted((s, cone_canon(vs)) for s, vs in by_src.items()))


def canon_class(net):
    a = canon_network(net)
    b = canon_network([swap_r(r) for r in net])
    return min(a, b)


def rank2(net):
    vs = [vec(r) for r in net]
    return any(cross(u, v) != 0 for u, v in combinations(vs, 2))


def all_networks():
    return [tuple(sorted(c)) for c in combinations(REACTIONS, 4) if rank2(c)]


def classes():
    """Map canonical class -> list of member networks (sorted reaction tuples)."""
    cl = {}
    for net in all_networks():
        cl.setdefault(canon_class(net), []).append(net)
    return cl


def net_str(net):
    return ", ".join(rname(r) for r in net)


def parse_net(s):
    inv = {v: k for k, v in NAMES.items()}
    out = []
    for part in s.split(","):
        a, b = part.strip().split("->")
        out.append((inv[a.strip()], inv[b.strip()]))
    return tuple(sorted(out))


