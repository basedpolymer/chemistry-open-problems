// pt_auto.cpp -- independent re-implementation of the Ponitz-Tittmann (2000) finite-memory automaton A(d,k),
// written from the description in their Section 2 (not from the solver's code):
//  * a state is a walk r = (B = v_l, ..., v_1, v_0 = A) that "could be the first part of a loop of length <= k",
//    i.e. l + delta(r) <= k with delta = length of a shortest lattice path from A to B avoiding v_1..v_{l-1};
//  * from r, a step onto v_1..v_l closes a loop of length <= k (dropped: we count walks without such loops);
//    otherwise the augmented walk loses its oldest steps until it is admissible again;
//  * states are identified up to the 2^d d! lattice symmetries (canonical form: axes relabelled in order of
//    first appearance, first step along each axis positive).
// Reachable states from the empty walk are generated by BFS; the growth rate is bracketed by the
// Collatz-Wielandt min/max ratios of a power-iteration vector (floating point, for comparison with Table 2 only).
// Build: g++ -O2 -march=native -std=c++17 pt_auto.cpp -o pt_auto ; usage: pt_auto d k [iterations]
#include <bits/stdc++.h>
using namespace std;
typedef long long i64; typedef unsigned long long u64;
static int D, K, B;
static i64 DEL[16]; static i64 ORIG = 0; static const int SH = 7;

static int l1(i64 p) { int s = 0; for (int a = 0; a < D; a++) { int x = (int)((p >> (SH * a)) & 127) - 64; s += abs(x); } return s; }

// walk given by steps t[0..l) (t[0] newest), positions p_0 = 0, p_{i+1} = p_i - e(t_i)
static bool admissible(const vector<int>& t) {
    int l = (int)t.size();
    if (l <= 1) return true;  // empty walk; single step (delta = 1, loop of length 2)
    vector<i64> pos(l + 1); pos[0] = ORIG;
    for (int i = 0; i < l; i++) pos[i + 1] = pos[i] - DEL[t[i]];
    i64 Bp = pos[l];
    int budget = K - l;               // need delta <= budget
    // Manhattan lower bound
    auto dist1 = [&](i64 p) { int s = 0; for (int a = 0; a < D; a++) { int x = (int)((p >> (SH * a)) & 127) - (int)((Bp >> (SH * a)) & 127); s += abs(x); } return s; };
    if (dist1(ORIG) > budget) return false;
    unordered_set<i64> blocked(pos.begin() + 1, pos.begin() + l);  // v_1..v_{l-1}
    // BFS from A with pruning depth + |p-B|_1 <= budget
    unordered_set<i64> seen; seen.insert(ORIG);
    vector<i64> cur{ORIG}, nxt;
    for (int depth = 0; depth < budget; depth++) {
        nxt.clear();
        for (i64 p : cur) for (int dir = 0; dir < 2 * D; dir++) {
            i64 q = p - DEL[dir];
            if (q == Bp) return true;  // reached B in depth+1 <= budget steps
            if (blocked.count(q) || seen.count(q)) continue;
            if (depth + 1 + dist1(q) > budget) continue;
            seen.insert(q); nxt.push_back(q);
        }
        cur.swap(nxt);
        if (cur.empty()) break;
    }
    return false;
}

static u64 canon(const vector<int>& t) {
    int img[8], sg[8]; for (int a = 0; a < 8; a++) img[a] = -1; int nl = 0;
    if ((int)t.size() * B > 57) { fprintf(stderr, "walk too long for the encoding\n"); exit(3); }
    u64 c = (u64)t.size() << 57;
    for (size_t k = 0; k < t.size(); k++) { int a = t[k] >> 1, b = t[k] & 1; if (img[a] < 0) { img[a] = nl++; sg[a] = b; }
        c |= (u64)(2 * img[a] + (b ^ sg[a])) << (B * k); }
    return c;
}
static vector<int> decodeSteps(u64 c) { int l = (int)(c >> 57); vector<int> t(l); for (int k = 0; k < l; k++) t[k] = (int)((c >> (B * k)) & ((1 << B) - 1)); return t; }

int main(int argc, char** argv) {
    D = atoi(argv[1]); K = atoi(argv[2]); int iters = argc > 3 ? atoi(argv[3]) : 3000;
    B = D <= 2 ? 2 : (D <= 4 ? 3 : 4);   // (a first version used 3 bits for d = 2: overflow at k = 22, fixed)
    for (int a = 0; a < D; a++) { DEL[2 * a] = (i64)1 << (SH * a); DEL[2 * a + 1] = -((i64)1 << (SH * a)); ORIG += (i64)64 << (SH * a); }
    auto T0 = chrono::steady_clock::now();
    unordered_map<u64, int> idx; vector<u64> codes;
    vector<array<int, 12>> succ;  // -1 = loop closed (dropped)
    idx[canon({})] = 0; codes.push_back(canon({}));
    for (size_t s = 0; s < codes.size(); s++) {
        vector<int> t = decodeSteps(codes[s]); int l = (int)t.size();
        vector<i64> pos(l + 1); pos[0] = ORIG; for (int i = 0; i < l; i++) pos[i + 1] = pos[i] - DEL[t[i]];
        array<int, 12> sc; sc.fill(-1);
        for (int dir = 0; dir < 2 * D; dir++) {
            i64 e = ORIG + DEL[dir];
            bool hit = false; for (int i = 1; i <= l; i++) if (pos[i] == e) { hit = true; break; }
            if (hit) continue;  // closes a loop of length <= k
            vector<int> a; a.reserve(l + 1); a.push_back(dir); for (int x : t) a.push_back(x);
            while (!admissible(a)) a.pop_back();
            u64 c = canon(a);
            auto it = idx.find(c); int j;
            if (it == idx.end()) { j = (int)codes.size(); idx[c] = j; codes.push_back(c); } else j = it->second;
            sc[dir] = j;
        }
        succ.push_back(sc);
    }
    size_t N = codes.size();
    double tg = chrono::duration<double>(chrono::steady_clock::now() - T0).count();
    // power iteration on (A + I) for aperiodicity safety; CW bracket on A
    vector<double> v(N, 1.0), w(N);
    double lo = 0, hi = 0;
    for (int it = 0; it < iters; it++) {
        double mx = 0;
        for (size_t s = 0; s < N; s++) { double acc = v[s]; for (int dir = 0; dir < 2 * D; dir++) if (succ[s][dir] >= 0) acc += v[succ[s][dir]]; w[s] = acc; mx = max(mx, acc); }
        for (size_t s = 0; s < N; s++) v[s] = w[s] / mx;
        if (it % 100 == 99 || it == iters - 1) {
            lo = 1e300; hi = 0;
            for (size_t s = 0; s < N; s++) { double acc = 0; for (int dir = 0; dir < 2 * D; dir++) if (succ[s][dir] >= 0) acc += v[succ[s][dir]];
                if (v[s] > 0) { lo = min(lo, acc / v[s]); hi = max(hi, acc / v[s]); } }
            if (hi - lo < 1e-11) break;
        }
    }
    double tt = chrono::duration<double>(chrono::steady_clock::now() - T0).count();
    printf("d=%d k=%d reachable states=%zu  CW bracket [%.10f, %.10f]  (gen %.1f s, total %.1f s)\n", D, K, N, lo, hi, tg, tt);
}
